#: Denominator kinds whose raw scores may be compared across scripts.
DIRECTLY_COMPARABLE = {"closed_inventory"}

_UNKNOWN = ("unknown", "closed_inventory")


def script_type(script: str) -> str:
    """Return the typological class of an ISO 15924 script code."""
    return SCRIPT_TYPES.get(script, _UNKNOWN)[0]


def denominator_kind(script: str) -> str:
    """
    Return how the CLDR exemplar set for this script relates to the script's
    real character inventory. See the module docstring for the four values.
    """
    return SCRIPT_TYPES.get(script, _UNKNOWN)[1]


def is_comparable(script: str) -> bool:
    """
    True when a raw weighted score for this script can be placed on the same
    axis as scores for other scripts.
    """
    return denominator_kind(script) in DIRECTLY_COMPARABLE


def comparability(script: str) -> str:
    """``"direct"`` or ``"within_script_only"`` — how this score may be read."""
    return "direct" if is_comparable(script) else "within_script_only"


# ---------------------------------------------------------------------------
# Normalization for combinatorial scripts
# ---------------------------------------------------------------------------

@dataclass
class Normalization:
    """
    A principled alternative denominator for a combinatorial script.

    Attributes:
        codepoints: The generator set — the components a model needs in order to
            compose every unit in the original exemplar set.
        kind:       Identifier for the decomposition applied.
        note:       Human-readable justification, surfaced in the dashboard.
    """

    codepoints: set[int]
    kind: str
    note: str


def normalize_exemplars(script: str, codepoints: set[int]) -> Normalization | None:
    """
    Return a generator-set normalization for ``codepoints``, or None when no
    principled one exists for this script.

    Only ``combinatorial`` scripts are normalizable. Hangul syllable blocks
    (U+AC00–U+D7A3) decompose canonically to conjoining Jamo under NFD, so the
    generator set is well defined and small. Han ideographs do not decompose to
    a closed component set in Unicode, and syllabic scripts such as Ethiopic
    have no uniform canonical decomposition, so both return None.
    """
    if denominator_kind(script) != "combinatorial":
        return None

    jamo: set[int] = set()
    passthrough: set[int] = set()
    for cp in codepoints:
        decomposed = unicodedata.normalize("NFD", chr(cp))
        if len(decomposed) > 1:
            jamo.update(ord(ch) for ch in decomposed)
        else:
            passthrough.add(cp)

    if not jamo:
        return None

    return Normalization(
        codepoints=jamo | passthrough,
        kind="hangul_jamo",
        note=(
            f"{len(codepoints)} precomposed Hangul syllables are generated by "
            f"{len(jamo)} conjoining Jamo; scoring against the Jamo measures "
            "whether the model can compose Korean rather than whether it "
            "memorised every syllable block."
        ),
    )
