"""
Script typology and score comparability.

Why this module exists
----------------------
loove's headline metric divides a weighted tier sum by the size of the language's
CLDR exemplar set. That denominator is not a neutral quantity: it reflects how
CLDR chose to enumerate a writing system, and that choice varies by three orders
of magnitude across scripts.

    script  median exemplar set
    Kore              11172      precomposed Hangul syllables
    Hant               2470      Han ideographs (frequency sample)
    Jpan               2311      kana + Han
    Ethi                295      syllabic Ethiopic
    Deva                 65      consonants + vowel signs
    Latn                 28      letters

Across the 310 languages in the database, the correlation between log10 exemplar
set size and mean weighted score is r = -0.60. Roughly a third of the variance in
loove's headline number is explained by the denominator alone, before any
property of the tokenizer is considered. Korean is the extreme case: its mean
score across ingested models is 0.15, the lowest of any major language, because
its denominator is all 11,172 precomposed Hangul syllable blocks. The same text
is generated from 67 Jamo, and a model holding those 67 can compose every
syllable — yet under the raw metric it scores near zero.

Cross-script leaderboards built on the raw score therefore rank scripts, not
tokenizers. This module classifies each script so that consumers can say which
comparisons are legitimate, and supplies a principled normalization where one
exists.

Denominator kinds
-----------------
``closed_inventory``
    The exemplar set is approximately the script's actual character inventory:
    alphabets, abjads, and abugidas. Scores are directly comparable to each
    other.

``combinatorial``
    The exemplar set enumerates precomposed units generated by a smaller set of
    components — Hangul syllable blocks from Jamo. A normalized score against
    the generator set is well defined, so both are reported.

``open_set``
    The exemplar set is a frequency-based sample of an open-ended repertoire
    (Han ideographs). There is no canonical denominator: the number is a
    property of CLDR's cut-off, not of the script. Comparable only against the
    same script.

``syllabic_derived``
    A closed but combinatorially generated syllabary (Ethiopic, Vai, Cherokee,
    Canadian Aboriginal). Inventories are large relative to alphabets, and CLDR
    lists surface syllables. Treated as within-script-comparable rather than
    normalized, since the component decomposition is not uniformly expressible
    in Unicode.
"""
